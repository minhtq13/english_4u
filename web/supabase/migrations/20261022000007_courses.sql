-- Lesson list now includes the label and course (new columns go last so the view can be replaced in place).
create or replace view public.lesson_overview
with (security_invoker = true) as
select
  l.id,
  l.phase_id,
  l.position,
  l.title,
  l.description,
  l.is_published,
  coalesce((
    select count(*)
    from public.section_items i
    join public.lesson_sections s on s.id = i.section_id
    where s.lesson_id = l.id and s.score_key is not null
  ), 0)::integer as scored_items,
  l.label,
  p.course_id
from public.lessons l
join public.phases p on p.id = l.phase_id;

-- Per-lesson numbers for the teacher's statistics (RLS on attempts limits learners to their own rows).
create view public.lesson_stats
with (security_invoker = true) as
select
  o.id as lesson_id,
  o.course_id,
  o.label,
  o.title,
  o.position,
  o.scored_items,
  count(a.id)::integer as learners,
  (count(a.id) filter (where o.scored_items > 0 and coalesce((a.score ->> 'done')::integer, 0) >= o.scored_items))::integer as completed,
  (count(a.id) filter (where a.status = 'submitted'))::integer as waiting,
  (count(a.id) filter (where a.status = 'graded'))::integer as graded,
  round(100.0 * sum(coalesce((a.score ->> 'ok')::integer, 0))
        / nullif(sum(coalesce((a.score ->> 'done')::integer, 0)), 0))::integer as accuracy
from public.lesson_overview o
left join public.attempts a on a.lesson_id = o.id
group by o.id, o.course_id, o.label, o.title, o.position, o.scored_items;

-- Recurring errors per course: the lesson's course when known, otherwise the learner's.
create view public.course_error_stats
with (security_invoker = true) as
select
  coalesce(ph.course_id, p.course_id) as course_id,
  e.category,
  e.status,
  count(*)::integer as entries,
  sum(e.occurrences)::integer as occurrences
from public.error_log e
join public.profiles p on p.id = e.user_id
left join public.lessons l on l.id = e.lesson_id
left join public.phases ph on ph.id = l.phase_id
group by 1, 2, 3;
