create or replace function public.guard_profile_update()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  -- auth.uid() is null for SQL run from the dashboard / migrations: allowed.
  if (select auth.uid()) is not null and not public.is_admin()
     and (new.role is distinct from old.role or new.email is distinct from old.email) then
    raise exception 'Bạn chỉ được đổi lớp học và tên hiển thị';
  end if;
  return new;
end;
$$;

create trigger profiles_guard_update
  before update on public.profiles
  for each row execute function public.guard_profile_update();

