-- Courses group the content: one per school grade (lớp 6–9, THCS) plus standalone tracks
-- (the original B1→B2 grammar lessons). Each learner picks the course they follow.
--   courses → phases → lessons → lesson_sections → section_items
-- Grade lessons use ids "<grade>.<unit>" (6.1 = lớp 6, Unit 1) and show their label ("Unit 1").

create type public.course_kind as enum ('grade', 'track');

create table public.courses (
  id text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  kind public.course_kind not null,
  grade smallint check (grade between 1 and 12),       -- set for kind = 'grade'
  name text not null,
  description text not null default '',
  position integer not null,                           -- order on the "choose your class" page
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  constraint grade_matches_kind check ((kind = 'grade') = (grade is not null))
);
comment on table public.courses is 'Khoá học: mỗi lớp (6–9) là một khoá; khoá loại track không thuộc lớp nào.';

